#!/usr/bin/env python3
"""Builds the GoHighLevel loaders in bf/ghl/*.js from the Black Friday checkout pages.

Each GHL funnel page (funnel "Black Friday Checkout ($1,250)") holds ONE line of custom code:
    <script src="https://javmartz04-ship-it.github.io/rig-marketing-machine-optin/bf/ghl/<page>.js"></script>
The loader mounts the whole page over the empty GHL page. To change a page: edit the .html, run this, push.

Run:  python3 bf/build_ghl.py
"""
import json, re, pathlib

ROOT = pathlib.Path(__file__).parent
BASE = 'https://javmartz04-ship-it.github.io/rig-marketing-machine-optin/'
PAGES = {'checkout.html': 'checkout', 'onboarding.html': 'onboarding', 'welcome.html': 'welcome'}
SLUGS = {"var WELCOME = 'welcome.html'": "var WELCOME = '/bf-welcome'"}

def absolutize(t):
    t = re.sub(r'''(["'(])\.\./assets/''', lambda m: m.group(1) + BASE + 'assets/', t)
    t = re.sub(r'''(["'(])assets/''', lambda m: m.group(1) + BASE + 'bf/assets/', t)
    return t

css = absolutize((ROOT / 'bf.css').read_text().replace('url(../assets/', 'url(' + BASE + 'assets/'))

for src, name in PAGES.items():
    html = (ROOT / src).read_text()
    for a, b in SLUGS.items():
        html = html.replace(a, b)
    html = html.replace('<link rel="stylesheet" href="bf.css">', '<style>' + css + '</style>')
    html = absolutize(html)
    head = re.search(r'<head>(.*?)</head>', html, re.S).group(1)
    body = re.search(r'<body[^>]*>(.*)</body>', html, re.S).group(1)
    title = re.search(r'<title>(.*?)</title>', head, re.S).group(1)
    scripts = []
    def take(m):
        scripts.append(m.group(2)); return ''
    body = re.sub(r'<script([^>]*)>(.*?)</script>', take, body, flags=re.S)
    head = re.sub(r'<title>.*?</title>|<meta charset[^>]*>|<meta name="viewport"[^>]*>', '', head, flags=re.S)
    assert not re.search(r'''["'(]\.?\.?/?assets/''', head + body), src + ': relative asset left'
    js = '''/* Generated by bf/build_ghl.py from %s. Do not edit by hand. */
(function () {
  if (window.__rigbf) return; window.__rigbf = 1;
  var HEAD = %s, BODY = %s, SCRIPTS = %s, TITLE = %s;
  var d = document;
  d.title = TITLE;
  if (!d.querySelector('meta[name=viewport]')) { var m = d.createElement('meta'); m.name = 'viewport'; m.content = 'width=device-width,initial-scale=1'; d.head.appendChild(m); }
  var hide = d.createElement('style');
  hide.textContent = 'body>*:not(#bfp):not(script):not(style):not(link){display:none!important}html,body{margin:0!important;padding:0!important;background:#F6F5F1!important}';
  d.head.appendChild(hide);
  d.head.insertAdjacentHTML('beforeend', HEAD);
  function mount() {
    var t = d.createElement('div'); t.innerHTML = BODY;
    while (t.firstChild) d.body.appendChild(t.firstChild);
    SCRIPTS.forEach(function (c) { var el = d.createElement('script'); el.text = c; d.body.appendChild(el); });
  }
  if (d.body) mount(); else d.addEventListener('DOMContentLoaded', mount);
})();
''' % (src, json.dumps(head), json.dumps(body), json.dumps(scripts), json.dumps(title))
    js = js.replace('</script', '<\\/script')
    out = ROOT / 'ghl' / (name + '.js')
    out.parent.mkdir(exist_ok=True)
    out.write_text(js)
    print('%-16s -> bf/ghl/%s.js  %d KB' % (src, name, len(js) // 1024))
